/**
 * Helper to fetch colleges for a university
 */
export const getAffiliatedCollegesByUniversity = (universityId: string): AffiliatedCollege[] => {
  const norm = (universityId || '').toLowerCase().trim();
  if (norm.includes('makaut') || norm.includes('wbut')) {
    return MAKAUT_AFFILIATED_COLLEGES;
  }
  if (norm.includes('calcutta') || norm.includes('cu')) {
    return CU_AFFILIATED_COLLEGES;
  }
  return [];
};
