/**
 * Filter MAKAUT programmes by query, category, and type
 */
export const searchMakautProgrammes = (
  query: string,
  category?: string,
  type?: string
): MakautProgramme[] => {
  const q = (query || '').toLowerCase().trim();
  return MAKAUT_PROGRAMMES.filter(p => {
    if (category && category !== 'all' && p.category !== category) return false;
    if (type && type !== 'all' && p.type !== type) return false;
    if (!q) return true;
    return (
      p.name.toLowerCase().includes(q) ||
      p.shortName.toLowerCase().includes(q) ||
      p.code.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      (p.department && p.department.toLowerCase().includes(q)) ||
      (p.badge && p.badge.toLowerCase().includes(q))
    );
  });
};

/**
 * Get programmes by type
 */
export const getMakautProgrammesByType = (type: MakautProgrammeType): MakautProgramme[] => {
  return MAKAUT_PROGRAMMES.filter(p => p.type === type);
};

/**
 * Get programmes by category
 */
export const getMakautProgrammesByCategory = (category: MakautCategory): MakautProgramme[] => {
  return MAKAUT_PROGRAMMES.filter(p => p.category === category);
};
