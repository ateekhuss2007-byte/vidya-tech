export const getUniversityById = (id: string): UniversityMeta => {
  return PAN_INDIA_UNIVERSITIES.find(u => u.id === id) || PAN_INDIA_UNIVERSITIES[0];
};

export const getUniversitiesByAuthority = (authority: AuthorityType | 'all'): UniversityMeta[] => {
  if (authority === 'all') return PAN_INDIA_UNIVERSITIES;
  return PAN_INDIA_UNIVERSITIES.filter(u => u.authorityType === authority);
};
